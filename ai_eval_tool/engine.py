"""
Evaluation Engine: Orchestrates the entire evaluation process.
"""
import polars as pl
import json
from pathlib import Path
from typing import Dict, Any

from .config_manager import MainConfig
from .evaluators.performance import PerformanceEvaluator
from .evaluators.stability.factory import StabilityEvaluatorFactory
from .utils.types import EvaluationResult
from .utils.logging_config import get_logger

logger = get_logger(__name__)

class EvaluationEngine:
    """
    The EvaluationEngine coordinates the different evaluation steps,
    calling performance and stability evaluators and aggregating their results.
    It also handles serialization and deserialization of evaluation results for caching.
    """
    def __init__(self, config: MainConfig):
        self.config = config
        self.performance_evaluator = PerformanceEvaluator(config)
        self.stability_evaluator_factory = StabilityEvaluatorFactory()
        logger.info("EvaluationEngine initialized.")

    def run(self, data_df: pl.DataFrame) -> EvaluationResult:
        """
        Executes the full evaluation pipeline on the given data.
        """
        logger.info("Evaluation process started by EvaluationEngine.")

        all_metrics: Dict[str, Any] = {}
        all_plots: Dict[str, Any] = {}
        all_extra_data: Dict[str, Any] = {}

        logger.info("Running Performance Evaluator...")
        # Use shallow clone to save memory - evaluators should not modify the original data
        perf_results: EvaluationResult = self.performance_evaluator.evaluate(data_df.clone())
        all_metrics.update(perf_results.metrics)
        all_extra_data.update(perf_results.extra_data)
        logger.info(f"Performance evaluation completed. Metrics calculated: {list(perf_results.metrics.keys())}")

        model_type = self.config.project_info.model_type
        logger.info(f"Attempting to run Stability Evaluator for model type: {model_type}...")
        try:
            stability_evaluator = self.stability_evaluator_factory.get_evaluator(model_type, self.config)
            # Use shallow clone to save memory - evaluators should not modify the original data
            stability_results: EvaluationResult = stability_evaluator.evaluate(data_df.clone())
            all_metrics.update(stability_results.metrics)
            all_extra_data.update(stability_results.extra_data)
            logger.info(f"Stability evaluation for {model_type} completed. Metrics calculated: {list(stability_results.metrics.keys())}")
        except ValueError as e:
            logger.error(f"Could not get or run stability evaluator for model type '{model_type}': {e}")
            logger.warning("Proceeding with only performance metrics if stability evaluation failed.")
        except Exception as e:
            logger.error(f"An unexpected error occurred during stability evaluation for '{model_type}': {e}", exc_info=True)
            logger.warning("Proceeding with only performance metrics due to unexpected stability evaluation error.")

        if not all_metrics:
            logger.warning("No metrics were generated by any evaluator.")
            all_metrics["engine_warning"] = "No metrics generated."
        else:
            # Calculate S_total score if individual scores are present
            s_performance = all_metrics.get("perf_score_overall")

            model_stab_score_key = None
            if model_type == "detection": model_stab_score_key = "det_stab_score_overall"
            elif model_type == "classification": model_stab_score_key = "cls_stab_score_overall"
            elif model_type == "rotated_detection": model_stab_score_key = "rdt_stab_score_overall"
            elif model_type == "pose": model_stab_score_key = "pos_stab_score_overall"

            s_model_stability = None
            if model_stab_score_key:
                s_model_stability = all_metrics.get(model_stab_score_key)

            if s_performance is not None and s_model_stability is not None and \
               hasattr(self.config.evaluation_params, 'overall_scoring_weights') and \
               self.config.evaluation_params.overall_scoring_weights is not None:

                overall_weights = self.config.evaluation_params.overall_scoring_weights
                w_perf = overall_weights.performance
                w_stab = overall_weights.stability

                s_total = (s_performance * w_perf) + (s_model_stability * w_stab)

                # Normalize if weights don't sum to 1 (though Pydantic model could enforce this)
                # For now, assume weights are valid [0,1] and sum to 1 or are handled by user.
                # If strict sum-to-1 normalization is needed:
                # total_w = w_perf + w_stab
                # if abs(total_w - 1.0) > 1e-6 and total_w > 1e-6:
                #    s_total = s_total / total_w

                all_metrics["total_score_overall"] = max(0.0, min(100.0, s_total))
                logger.info(f"Calculated Total Overall Score: {all_metrics['total_score_overall']:.2f} (S_perf={s_performance:.2f} * wP={w_perf} + S_stab={s_model_stability:.2f} * wS={w_stab})")
            elif s_performance is not None :
                 all_metrics["total_score_overall"] = s_performance
                 logger.info(f"Total Overall Score set to S_Performance ({s_performance:.2f}) as stability score was unavailable.")
            elif s_model_stability is not None:
                 all_metrics["total_score_overall"] = s_model_stability
                 logger.info(f"Total Overall Score set to S_Stability ({s_model_stability:.2f}) as performance score was unavailable.")


        final_results = EvaluationResult(
            metrics=all_metrics,
            plots=all_plots, # Plots are generated by ReportGenerator, not stored here directly
            extra_data=all_extra_data
        )

        logger.info("Evaluation process completed by EvaluationEngine.")
        return final_results

    def serialize_results(self, results: EvaluationResult, cache_base_path: Path, run_id: str):
        """
        Serializes the EvaluationResult object.
        Metrics are saved to a JSON file. DataFrames in extra_data are saved to Parquet files.
        The main JSON file will store paths to these Parquet files.
        Cache structure: <cache_base_path>/<run_id>/
                           - results.json
                           - extra_data_key1.parquet
                           - extra_data_key2.parquet
        """
        run_cache_dir = cache_base_path / run_id
        run_cache_dir.mkdir(parents=True, exist_ok=True)

        logger.info(f"Serializing evaluation results to directory: {run_cache_dir.resolve()}")

        output_meta = {
            "metrics": results.metrics,
            "extra_data_paths": {} # Stores relative paths to parquet files
        }

        for key, data_item in results.extra_data.items():
            if isinstance(data_item, pl.DataFrame):
                parquet_filename = f"extra_data_{key}.parquet"
                parquet_path = run_cache_dir / parquet_filename
                try:
                    data_item.write_parquet(parquet_path)
                    output_meta["extra_data_paths"][key] = parquet_filename # Store just filename, relative to run_cache_dir
                    logger.debug(f"Serialized DataFrame '{key}' to {parquet_path}")
                except Exception as e:
                    logger.error(f"Failed to serialize DataFrame '{key}' to Parquet: {e}")
            else:
                logger.warning(f"Item '{key}' in extra_data is not a Polars DataFrame and will not be serialized to Parquet. Type: {type(data_item)}")

        results_json_path = run_cache_dir / "results.json"
        try:
            with open(results_json_path, 'w', encoding='utf-8') as f:
                json.dump(output_meta, f, indent=4)
            logger.info(f"Serialized metrics and extra_data metadata to {results_json_path}")
        except Exception as e:
            logger.error(f"Failed to serialize results to JSON: {e}")
            raise

    def deserialize_results(self, cache_base_path: Path, run_id: str) -> EvaluationResult:
        """
        Deserializes EvaluationResult from cached files.
        Assumes cache structure created by serialize_results.
        """
        run_cache_dir = cache_base_path / run_id
        results_json_path = run_cache_dir / "results.json"

        logger.info(f"Deserializing evaluation results from: {results_json_path.resolve()}")

        if not results_json_path.exists():
            logger.error(f"Cache metadata file not found: {results_json_path}")
            raise FileNotFoundError(f"Cache metadata file not found: {results_json_path}")

        try:
            with open(results_json_path, 'r', encoding='utf-8') as f:
                cached_meta = json.load(f)
        except Exception as e:
            logger.error(f"Failed to load or parse cache metadata JSON: {e}")
            raise

        metrics = cached_meta.get("metrics", {})
        extra_data_paths = cached_meta.get("extra_data_paths", {})
        extra_data: Dict[str, Any] = {}

        for key, parquet_filename in extra_data_paths.items():
            parquet_path = run_cache_dir / parquet_filename
            if parquet_path.exists():
                try:
                    extra_data[key] = pl.read_parquet(parquet_path)
                    logger.debug(f"Deserialized DataFrame '{key}' from {parquet_path}")
                except Exception as e:
                    logger.error(f"Failed to deserialize DataFrame '{key}' from Parquet {parquet_path}: {e}")
                    extra_data[key] = f"Error loading {parquet_filename}"
            else:
                logger.warning(f"Parquet file for extra_data key '{key}' not found at {parquet_path}")
                extra_data[key] = f"File not found: {parquet_filename}"

        return EvaluationResult(metrics=metrics, plots={}, extra_data=extra_data)


